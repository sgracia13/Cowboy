package habits

import (
	"fmt"
	"sort"
	"strings"

	"github.com/sgracia13/Cowboy/internal/config"
)

// The guide sits between these markers in AGENTS.md, CLAUDE.md or
// .github/copilot-instructions.md, so running it again replaces the
// section instead of adding another.
const (
	Start = "<!-- cowboy:guide start -->"
	End   = "<!-- cowboy:guide end -->"
)

var shortcutRules = []struct{ kind, line string }{
	{"suppressions", "Don't silence warnings or type errors to get checks passing (`eslint-disable`, `# type: ignore`, `@SuppressWarnings`, `//nolint`). Fix the cause, or say in the pull request why the warning is wrong."},
	{"skips", "Don't skip tests (`.skip`, `@pytest.mark.skip`, `t.Skip`, `@Disabled`) to get a change through."},
	{"tests_removed", "Don't delete tests or remove assertions. If a test is wrong, fix it and say why."},
	{"ci_loosened", "Don't loosen CI: no `|| true`, `continue-on-error`, removed steps or weaker test settings."},
	{"catch_all", "Don't add catch-alls that swallow errors (an empty `catch`, `except: pass`, ignoring returned errors)."},
	{"special_case_comments", "Don't add special cases that only exist to make a test pass."},
}

// Guide writes the agent guidance section for a repo: its review rules,
// the shortcuts Cowboy flags, its habits, and how to disclose agent work.
// rep may be empty (no history yet).
func Guide(repo string, cfg config.Config, rep Report) string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	w("%s\n## Working in %s\n\n", Start, repo)
	w("These notes come from this repo's review rules and its own history, generated by Cowboy. Run `cowboy guide` to refresh them; edit anything outside the markers freely.\n\n")

	w("### What gets a closer review\n\n")
	if len(cfg.Careful.Paths) > 0 {
		paths := append([]string(nil), cfg.Careful.Paths...)
		sort.Strings(paths)
		w("- Changes under %s are sent for careful review. Keep them small and explain why in the description.\n", "`"+strings.Join(paths, "`, `")+"`")
	}
	if cfg.Careful.MinFanIn > 0 {
		w("- Changes to files that many others import (this repo's most-imported files) are sent for careful review. Prefer adding new code over changing widely used code when either works.\n")
	}
	w("- Failing checks send a pull request to careful review. Run the tests before opening one.\n")
	if cfg.Easy.MaxLines > 0 {
		w("- Pull requests of %d lines or fewer, in %d folders or fewer, get the quickest review. One concern per pull request.\n", cfg.Easy.MaxLines, cfg.Easy.MaxDirs)
	}
	if cfg.Notes.BigSourceLines > 0 {
		w("- Over %d lines of source is too big to review well in one sitting: split it.\n", cfg.Notes.BigSourceLines)
	}

	var short []string
	for _, s := range shortcutRules {
		if cfg.Shortcuts == nil || cfg.Shortcuts[s.kind] {
			short = append(short, s.line)
		}
	}
	if len(short) > 0 {
		w("\n### Don't take these shortcuts\n\nCowboy flags each of these on the pull request.\n\n")
		for _, l := range short {
			w("- %s\n", l)
		}
	}

	var shown []Row
	for _, r := range rep.Rows {
		if r.Applies >= 10 {
			shown = append(shown, r)
		}
	}
	if len(shown) > 0 {
		w("\n### This team's habits (last %d days)\n\n", rep.Days)
		for _, r := range shown {
			line := fmt.Sprintf("**%s**: %s. %.0f%% of pull requests here do this.", r.Name, r.What, 100*r.Share)
			// evidence notes belong on the Habits page; the guide only adds one
			// when this repo's history backs the habit
			if r.Verdict == Holds {
				line += fmt.Sprintf(" In this repo, pull requests that did had trouble after merge %.2f× as often as those that didn't, size held fixed.", r.RR)
			}
			w("- %s\n", line)
		}
	}

	w("\n### Check before you open a pull request\n\n")
	w("- Run `cowboy check` (or the Cowboy MCP tool `check_changes`) on your changes and fix what it flags, or say in the pull request why it's right.\n")
	w("\n### Say when an agent helped\n\n")
	w("- Add a trailer to commits an agent wrote or co-wrote, naming the agent, for example `Co-authored-by: Claude <noreply@anthropic.com>`. Reviewers then know what they're reading, and Cowboy tags the pull request.\n")
	w("%s\n", End)
	return b.String()
}

// Apply puts the guide into a file's text: it replaces an earlier Cowboy
// section, or adds one at the end.
func Apply(text, guide string) string {
	i, j := strings.Index(text, Start), strings.Index(text, End)
	if i >= 0 && j > i {
		return text[:i] + strings.TrimRight(guide, "\n") + text[j+len(End):]
	}
	if strings.TrimSpace(text) == "" {
		return guide
	}
	return strings.TrimRight(text, "\n") + "\n\n" + guide
}
